"""The "rock" art kit for tools/art/bake.py: rocky badlands over a concrete bunker (first used
by 08 Bunker, also meant for 09 Complex).

Read from the collision map plus level.json "art": {"interior": [[x0, y0, x1, y1], ...]}:

- outside the interior rects (the badlands):
  - open floor is dry ochre earth, with drifts of gravel and scree
  - walls are rock outcrops: weathered rock tops shaded as rounded lumps, with dark cliff
    sides extruded toward the camera
  - wide chasms are crevasses: broken rock falling away into the dark
  - thin chasms (at most `LOW` px from edge to middle: low cover you shoot over but can't
    cross) are sandbag walls
- inside them (the bunker), and for walls also inside "concrete": [[x0, y0, x1, y1], ...]
  (pillboxes, huts, revetments out in the badlands, whose floor stays earth):
  - open floor is poured concrete slabs, a little darker than outside
  - walls are reinforced concrete: a bunker roof inside a lighter coping, with concrete sides
  - thin chasms are low concrete barriers with a hazard-striped top; wide ones are pits

Textures in tools/art/parts/rock/, decor sprites in tools/art/parts/decor/rock-*/ (both
generated by tools/art/gen_rock.sh, prompts next to them).

level.json "art" options read here: "interior" (above) and "grade": "ochre" (the default,
warm hazy daylight) or "dusk" (lower, redder light).
"""
import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

PARTS = os.path.join(os.path.dirname(__file__), 'parts', 'rock')
LOW = 7.5          # a chasm at most this far from its edge to its middle is low cover, not a pit


def blur(a, s): return ndi.gaussian_filter(a.astype(np.float32), s, mode='nearest')


def load(name):
    from bake import make_seamless
    return make_seamless(np.array(Image.open(os.path.join(PARTS, name + '.png')).convert('RGB'), np.float32) / 255)


def tiled(g, t, scale, angle=0.0, off=(0.0, 0.0)):
    from bake import tiled as _t
    return _t(g, t, scale, angle, off)


def noise(H, W, cell, s, rng):
    """Smooth value noise, mean 0 and std 1."""
    n = blur(rng.random((H // cell + 2, W // cell + 2)).repeat(cell, 0).repeat(cell, 1)[:H, :W], s)
    return (n - n.mean()) / (n.std() + 1e-6)


# ---------------------------------------------------------------- reading the map
class Rock:
    """What the rock kit reads from the collision map, shared by placing and baking."""

    def __init__(self, g, art, seed):
        self.g = g
        W, H = g.W, g.H
        inside = np.zeros((H, W), bool)
        for x0, y0, x1, y1 in art.get('interior', []):
            inside[max(0, int(y0)):min(H, int(y1)), max(0, int(x0)):min(W, int(x1))] = True
        self.inside = inside
        # a soft version for blending textures across the boundary
        self.insidef = blur(inside, 2.0)
        # walls drawn as concrete: the interior, plus "concrete" rects (pillboxes, huts and
        # revetments out in the badlands, whose floor stays earth)
        conc = inside.copy()
        for x0, y0, x1, y1 in art.get('concrete', []):
            conc[max(0, int(y0)):min(H, int(y1)), max(0, int(x0)):min(W, int(x1))] = True
        self.concrete = conc
        self.concf = blur(conc, 1.5)
        solid = g.wallb | g.chasmb
        self.open = ~solid
        self.wall_d = ndi.distance_transform_edt(~(g.wrb | (g.side > 0.5))).astype(np.float32)
        self.chasm_in = ndi.distance_transform_edt(g.chasmb).astype(np.float32)
        # low cover: chasm components no deeper than LOW px at their middle
        lab, n = ndi.label(g.chasmb)
        depth = ndi.maximum(self.chasm_in, lab, np.arange(1, n + 1)) if n else np.zeros(0)
        low_of = np.concatenate([[False], depth <= LOW])
        self.low = low_of[lab]
        self.pit = g.chasmb & ~self.low
        self.pit_d = ndi.distance_transform_edt(~self.pit).astype(np.float32)
        self.low_d = ndi.distance_transform_edt(~self.low).astype(np.float32)


# ---------------------------------------------------------------- step 1: decor surfaces + passes
PASSES = [
    # category, count, surface, short side, long side max, options (as bake.PASSES)
    ('rock-groundpaint', 30, 'ground', 26, 64, dict(effect='paint', along=False)),
    ('rock-floorpaint', 26, 'floor', 18, 46, dict(effect='paint', along=False)),
    ('rock-ground', 70, 'ground', 12, 34, dict(effect='shadow', strength=0.4, along=False)),
    ('rock-top', 26, 'rocktop', ('wall', 0.7, 54), 64, dict(along=False, max_scale=0.8, effect='shadow', strength=0.5)),
    ('rock-top', 70, 'rocktop', ('wall', 0.55, 26), 34, dict(along=False, max_scale=0.8, effect='shadow', strength=0.4)),
    ('rock-bunker', 40, 'bunkertop', ('wall', 0.6, 34), 44, dict(along=False, max_scale=0.8, effect='shadow', strength=0.5)),
    ('rock-lights', 46, 'lamps', 8, 12, dict(along=False, effect='glow', strength=0.85)),
]
CATEGORIES = ('rock-groundpaint', 'rock-floorpaint', 'rock-ground', 'rock-top', 'rock-bunker', 'rock-lights')


def surfaces(g, art, seed):
    r = Rock(g, art, seed)
    away = (r.pit_d > 10) & (r.low_d > 6)
    s = {
        'ground': ndi.binary_erosion(r.open & ~r.inside, iterations=4) & away & (r.wall_d >= 4),
        'floor': ndi.binary_erosion(r.open & r.inside, iterations=4) & away & (r.wall_d >= 6),
        'rocktop': ndi.binary_erosion(g.wrb & ~r.concrete, iterations=5),
        'bunkertop': ndi.binary_erosion(g.wrb & r.inside, iterations=9),
        # wall lamps: on the floor right at the foot of the bunker walls, where they'd be fixed
        'lamps': r.open & r.inside & (r.wall_d >= 3) & (r.wall_d <= 7) & away,
    }
    return s, {}, {}


# ---------------------------------------------------------------- step 2: the base art
def base_art(g, seed, opts, art):
    W, H = g.W, g.H
    r = Rock(g, art, seed)
    rng = np.random.default_rng(seed)
    inf = r.insidef[..., None]
    # ---- the ground outside: earth with drifts of gravel, warm light patches
    dirt = tiled(g, load('dirt'), 0.55)
    dirt = dirt / dirt.mean() * 0.42
    grav = tiled(g, load('gravel'), 0.42, off=(31, 17))
    grav = grav / grav.mean() * 0.40
    drift = np.clip(noise(H, W, 40, 22, rng) * 0.9 + 0.2 * noise(H, W, 8, 4, rng) - 0.1, 0, 1)
    drift = np.clip(drift + 0.6 * np.clip(1 - r.wall_d / 26, 0, 1) * (1 - r.inside), 0, 1)  # scree at the foot of the rocks
    ground = dirt * (1 - drift[..., None]) + grav * drift[..., None]
    ground *= (1 + 0.08 * noise(H, W, 60, 40, rng))[..., None]
    # ---- the bunker floor: concrete slabs, darker, light pooling away from the walls
    conc = tiled(g, load('concrete'), 0.5, off=(11, 3))
    conc = conc / conc.mean() * 0.36
    conc *= (0.78 + 0.22 * blur(np.clip(r.wall_d / 60, 0, 1), 8))[..., None]
    img = ground * (1 - inf) + conc * inf
    # ---- sun and shade: brighter in the open, a soft occlusion at the walls
    sun = 0.9 + 0.16 * blur(np.clip(r.wall_d / 90, 0, 1), 14)
    img *= np.where(r.inside, 1.0, sun)[..., None]
    # ---- pits: a crevasse outside, a dark pit inside
    ch = tiled(g, load('chasm'), 0.5, off=(37, 11))
    ch = ch / max(ch.mean(), 1e-3) * 0.19 * (1.15 - 0.7 * np.clip(r.chasm_in / 50, 0, 1))[..., None]
    pitm = (g.chasm * r.pit)[..., None]
    img = img * (1 - pitm) + ch * pitm
    # the crevasse's broken lip: ragged darker earth and a light rim
    rough = noise(H, W, 3, 1.2, rng)
    lip = r.open & (r.pit_d <= 6 + 3 * rough)
    img *= (1 - 0.3 * blur(lip, 1.0))[..., None]
    img = img + 0.12 * blur(r.open & (r.pit_d <= 1.8), 0.6)[..., None] * (1 - inf)
    # ---- low cover: sandbags outside, a concrete barrier with a hazard stripe inside
    lowf = blur(r.low & g.chasmb, 0.6) * np.clip(g.chasm * 1.4, 0, 1)
    # shadow on the floor south-east of the low walls
    lsh = blur(ndi.shift(r.low.astype(np.float32), (4, 4), order=0), 2.5) * (1 - lowf)
    img *= (1 - 0.5 * lsh * (1 - g.wr))[..., None]
    # bag rows run along each barrier: the direction of the barrier's distance field
    ly, lx = np.gradient(blur(r.chasm_in, 2))
    q = np.round((np.arctan2(ly, lx) + np.pi / 2) / (np.pi / 4)).astype(int) % 4
    q = ndi.median_filter(q, 5)
    sand_t = load('sandbag')
    bags = np.zeros_like(img)
    for k in range(4):
        bags += tiled(g, sand_t, 0.12, -k * np.pi / 4, off=(k * 53.0, k * 29.0)) * (q == k)[..., None]
    bags = bags / max(bags[r.low].mean() if r.low.any() else 1, 1e-3) * 0.55
    bar = tiled(g, load('bunker'), 0.35, off=(7, 41))
    bar = bar / bar.mean() * 0.62
    stripe = ((g.xx + g.yy) % 12 < 6)
    hz = np.where(stripe[..., None], np.array([0.74, 0.6, 0.16], np.float32), np.array([0.12, 0.11, 0.1], np.float32))
    ridge = np.clip(1 - np.abs(r.chasm_in - LOW * 0.5) / 2.2, 0, 1) * (r.chasm_in >= 2.5)
    bar = bar * (1 - 0.8 * ridge[..., None]) + hz * 0.8 * ridge[..., None]
    cf = r.concf[..., None]
    lowtop = bags * (1 - cf) + bar * cf
    # bevel the low walls: lit from the top-left
    hg = blur(np.clip(r.chasm_in / 4, 0, 1) * r.low, 0.8)
    gy, gx = np.gradient(hg)
    lam = (-gx * -0.55 - gy * -0.6 + 0.2 * 0.58) / np.sqrt(gx * gx + gy * gy + 0.04)
    lowtop *= (0.75 + 0.4 * lam)[..., None]
    img = img * (1 - lowf[..., None]) + lowtop * lowf[..., None]
    # ---- ambient occlusion where walls meet the floor
    ao = blur(np.maximum(g.side, g.wr), 5)
    img *= (1 - 0.45 * ao * (1 - g.wr) * (1 - g.side))[..., None]
    # cast shadow: the sun is up and to the left, so every wall throws a soft shadow down-right
    cast = blur(ndi.shift(np.maximum(g.wr, g.side), (7, 7), order=0), 3.5)
    img *= (1 - 0.38 * cast * (1 - g.wr) * (1 - 0.6 * r.insidef))[..., None]
    # ---- wall tops: rock outside, bunker roof inside
    rock = tiled(g, load('rock'), 0.5, off=(3, 91))
    rock = rock / rock.mean() * 0.56
    roof = tiled(g, load('bunker'), 0.45, off=(57, 13))
    roof = roof / roof.mean() * 0.6
    roof *= (1 - 0.18 * (r.concrete & ~r.inside))[..., None]     # pillboxes out in the sun: weathered darker
    # rock: rounded lumps (height grows with the distance into the rock), lit from the top-left
    hr = np.clip(g.dist / 16.0, 0, 1)
    hr = hr * hr * (3 - 2 * hr) + 0.15 * noise(H, W, 10, 4, rng) * np.clip(g.dist / 8, 0, 1)
    gy, gx = np.gradient(blur(hr, 1.0))
    nz = 0.09
    lr = (-gx * -0.55 - gy * -0.6 + nz * 0.58) / np.sqrt(gx * gx + gy * gy + nz * nz)
    rock *= (0.7 + 0.42 * lr)[..., None]
    rock *= (0.86 + 0.18 * np.clip(g.dist / 30, 0, 1))[..., None]          # tops catch the sun
    # bunker: a 6 px concrete coping round the roof, the roof a step lower
    cope = np.clip(1 - (g.dist - 6) / 1.2, 0, 1)
    inner = np.clip((g.dist - 6) / 4, 0, 1)
    roof = roof * (1 - cope[..., None]) + roof * 1.18 * cope[..., None]
    roof *= (1 - 0.2 * np.clip(1 - (g.dist - 6) / 3, 0, 1) * inner)[..., None]
    hb = np.clip(g.dist / 4.0, 0, 1); hb = blur(hb * hb * (3 - 2 * hb), 0.7)
    gy, gx = np.gradient(hb)
    lb = (-gx * -0.55 - gy * -0.6 + 0.18 * 0.58) / np.sqrt(gx * gx + gy * gy + 0.18 * 0.18)
    roof *= (0.72 + 0.4 * lb)[..., None]
    cf = r.concf[..., None]
    top = rock * (1 - cf) + roof * cf
    top *= (1 - 0.25 * np.clip(1 - g.dist / 1.2, 0, 1))[..., None]
    # ---- sides: darkened copies of the tops toward the camera point. Rock cliffs keep the
    # rock's grain and get warmer and darker the deeper they go; bunker walls are flat concrete
    sd = opts['sides']
    cliff = top * np.array([1.0, 0.93, 0.84], np.float32)
    for i in range(len(g.steps) - 1, -1, -1):
        coords, m = g.steps[i]
        if not m.any(): continue
        copy = np.stack([ndi.map_coordinates(cliff[..., k], coords, order=1, mode='nearest') for k in range(3)], -1)
        strata = 0.9 if i % 4 == 2 else 1.0
        copy *= sd['darken'] * sd['fade'] ** i * strata
        mm = (m * (1 - g.wr))[..., None]
        img = img * (1 - mm) + copy * mm
    return img * (1 - g.wr[..., None]) + top * g.wr[..., None]


# colour grades, picked by level.json "art": {"grade": name}: (pull toward grey, channel gains,
# lift). They live in tools/art/kits.json (with the kit's area lists), which the editor reads too.
KIT = json.load(open(os.path.join(os.path.dirname(__file__), 'kits.json')))['rock']
GRADES = {name: (g['grey'], tuple(g['gain']), g['haze']) for name, g in KIT['grades'].items()}


def grade(img, art):
    """The level's colour grade: warm hazy daylight (ochre) by default."""
    k, gain, lift = GRADES[art.get('grade') or KIT['defaultGrade']]
    lum = img.mean(-1, keepdims=True)
    img = lum + (img - lum) * (1 - k)
    return img * np.array(gain, np.float32) + lift
