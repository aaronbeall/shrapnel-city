"""The "city" art kit for tools/art/bake.py: city streets on a grey day (first used by 04 Urban).

Read from the collision map alone, like the Bridge kit:
- walls are buildings seen from above: flat roofs (one of three roof textures per building,
  picked by the seed) inside a light concrete parapet, with dark facades extruded toward the
  camera. Taller buildings have deeper facades. Thin or small walls (barriers, planters,
  rubble) are bare concrete and low.
- open floor is asphalt road with a pavement and kerb along every building; areas listed in
  level.json "art": {"paved": [[x0, y0, x1, y1], ...]} are paved all over (plazas, courtyards)
- road markings are drawn from the street shapes: dashed centre lines where a street is
  street-wide, zebra crossings round the crossings
- chasms are collapsed road: a broken asphalt edge falling into the subway

Textures in tools/art/parts/city/, decor sprites in tools/art/parts/decor/city-*/ (both
generated by tools/art/gen_city.sh, prompts next to them).
"""
import os

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

PARTS = os.path.join(os.path.dirname(__file__), 'parts', 'city')
ROOFS = ('roof', 'roof2', 'roof3')
KERB = 16          # pavement width along buildings, px
CENTRE = (40, 66)  # a street's half width range that gets a centre line
STREET = 150       # an open run across a street is at most this long; longer both ways is a crossing


def blur(a, s): return ndi.gaussian_filter(a.astype(np.float32), s, mode='nearest')


def load(name):
    from bake import make_seamless
    return make_seamless(np.array(Image.open(os.path.join(PARTS, name + '.png')).convert('RGB'), np.float32) / 255)


def tiled(g, t, scale, angle=0.0, off=(0.0, 0.0)):
    from bake import tiled as _t
    return _t(g, t, scale, angle, off)


def grey(img, k):
    """Pull colours toward their grey by k (0..1)."""
    lum = img.mean(-1, keepdims=True)
    return lum + (img - lum) * (1 - k)


def runs(mask, axis):
    """For each pixel of mask, the length of the unbroken run of mask through it along axis
    (1: its row, 0: its column)."""
    st = np.zeros((3, 3), int)
    if axis == 1: st[1, :] = 1
    else: st[:, 1] = 1
    lab, n = ndi.label(mask, st)
    size = np.bincount(lab.ravel())
    size[0] = 0
    return size[lab]


def line(mask, axis, r):
    """mask dilated r px along one axis only."""
    st = np.zeros((2 * r + 1, 2 * r + 1), bool)
    if axis == 1: st[r, :] = True
    else: st[:, r] = True
    return ndi.binary_dilation(mask, st)


# ---------------------------------------------------------------- reading the map
class City:
    """What the city kit reads from the collision map, shared by placing and baking."""

    def __init__(self, g, art, seed):
        self.g = g
        rng = np.random.default_rng(seed + 7)
        W, H = g.W, g.H
        lab, n = ndi.label(g.wrb)
        self.lab = lab
        idx = np.arange(1, n + 1)
        area = ndi.sum(np.ones_like(lab), lab, idx)
        depth = ndi.maximum(g.dist, lab, idx)
        sl = ndi.find_objects(lab)
        border = np.array([s[0].start == 0 or s[1].start == 0 or s[0].stop >= H or s[1].stop >= W for s in sl], bool)
        big = border | ((depth >= 14) & (area >= 3000))
        # per component: roof texture (0..2, -1 = bare concrete) and height in side copies
        self.roof = np.where(big, rng.integers(0, len(ROOFS), n), -1)
        steps = int(art.get('sides', {}).get('steps', 14))
        self.height = np.where(big, rng.integers(max(2, steps * 2 // 3), steps + 1, n), 3)
        self.height[border] = steps
        self.rot = rng.integers(0, 2, n)  # roof texture turned 90 degrees or not
        roof_of = np.concatenate([[-2], self.roof])
        self.buildings = roof_of[lab] >= 0
        self.small = g.wrb & ~self.buildings
        # the floor
        solid = g.wallb | g.chasmb
        self.open = ~solid
        self.open_d = ndi.distance_transform_edt(self.open).astype(np.float32)
        self.wall_d = ndi.distance_transform_edt(~(g.wrb | (g.side > 0.5))).astype(np.float32)
        self.chasm_d = ndi.distance_transform_edt(~g.chasmb).astype(np.float32)
        paved = np.zeros((H, W), bool)
        for x0, y0, x1, y1 in art.get('paved', []):
            paved[max(0, int(y0)):min(H, int(y1)), max(0, int(x0)):min(W, int(x1))] = True
        self.paved = paved & self.open
        self.road = self.open & (self.wall_d >= KERB) & ~self.paved
        self.pavement = self.open & ~self.road
        # how far the open floor runs through each pixel, along its row and its column: a street
        # running east-west is short in its column and long in its row, a crossing long in both
        self.hrun, self.vrun = runs(self.open, 1), runs(self.open, 0)
        self.hstreet = self.road & (self.vrun <= STREET) & (self.hrun > STREET)
        self.vstreet = self.road & (self.hrun <= STREET) & (self.vrun > STREET)
        self.crossing = self.road & (self.hrun > STREET) & (self.vrun > STREET)
        # street direction: across = the gradient of the open distance, along = its normal
        gy, gx = np.gradient(blur(self.open_d, 3))
        self.across = np.arctan2(gy, gx)
        self.street_q = ndi.median_filter(np.round((self.across + np.pi / 2) / (np.pi / 4)).astype(int) % 4, 5)


# ---------------------------------------------------------------- step 1: decor surfaces + passes
PASSES = [
    # category, count, surface, short side, long side max, options (as bake.PASSES)
    ('city-roadpaint', 22, 'road', 22, 54, dict(orient='street', effect='paint')),
    ('city-street', 46, 'road', 16, 40, dict(along=False)),
    ('city-street', 14, 'pavement', 10, 24, dict(along=False)),
    ('city-rubble', 40, 'lip', 12, 34, dict(effect='shadow', strength=0.4, along=False)),
    ('city-roof2', 14, 'roof', ('wall', 0.7, 74), 96, dict(along=False, max_scale=0.8, effect='shadow', strength=0.5)),
    ('city-roof', 70, 'roof', ('wall', 0.55, 34), 42, dict(along=False, max_scale=0.8, effect='shadow', strength=0.4)),
    ('city-plants', 12, 'planter', 40, 52, dict(along=False, max_scale=0.9, effect='shadow', strength=0.5, overhang=True)),
    ('city-lights', 26, 'kerb', 8, 11, dict(along=False, effect='glow', strength=0.8)),
]
CATEGORIES = ('city-roadpaint', 'city-street', 'city-rubble', 'city-roof2', 'city-roof', 'city-plants', 'city-lights')


def surfaces(g, art, seed):
    c = City(g, art, seed)
    s = {
        'road': ndi.binary_erosion(c.road, iterations=6),
        'pavement': ndi.binary_erosion(c.pavement, iterations=3) & (c.wall_d >= 3),
        'kerb': c.pavement & (c.wall_d >= 4) & (c.wall_d <= KERB - 1) & (c.chasm_d > 12) & ~c.paved,
        'lip': c.open & (c.chasm_d <= 12) & (c.chasm_d >= 2),
        'roof': ndi.binary_erosion(c.buildings & g.wrb, iterations=7),
        'planter': c.small & (g.dist >= 6) & (c.chasm_d > 30),
    }
    orients = {'street': c.street_q}
    reach = {'planter': ndi.binary_dilation(c.small, iterations=10) & ~g.chasmb}
    return s, orients, reach


# ---------------------------------------------------------------- step 2: the base art
def base_art(g, seed, opts, art):
    from bake import worn
    W, H = g.W, g.H
    c = City(g, art, seed)
    rng = np.random.default_rng(seed)
    road_t, pave_t, conc_t, chasm_t = (load(n) for n in ('road', 'pavement', 'concrete', 'chasm'))
    # road: asphalt, a little lighter in the middle of the street, patchy light from the clouds
    road = tiled(g, road_t, 0.5)
    road = road / road.mean() * 0.25
    clouds = blur(rng.random((H // 50 + 1, W // 50 + 1)).repeat(50, 0).repeat(50, 1)[:H, :W], 40)
    clouds = 1 + 0.16 * (clouds - clouds.mean()) / (clouds.std() + 1e-6) * 0.5
    road *= (0.9 + 0.14 * blur(np.clip(c.open_d / 70, 0, 1), 10))[..., None]
    pave = tiled(g, pave_t, 0.42, off=(17, 5))
    pave = pave / pave.mean() * 0.38
    img = np.where(c.road[..., None], road, pave)
    # kerb: a light kerb stone on the pavement's edge and a soft shadow on the road beside it
    kerb_band = c.open & (np.abs(c.wall_d - KERB) < 1.6) & ~c.paved
    kerb_band &= ndi.binary_dilation(c.road, iterations=2)
    kb = blur(kerb_band, 0.5)
    img = img * (1 - kb[..., None]) + 0.62 * kb[..., None]
    kshadow = blur(ndi.binary_dilation(kerb_band, iterations=2) & c.road, 1.2)
    img *= (1 - 0.35 * kshadow)[..., None]
    # road markings: dashed centre lines down the streets, zebra crossings at each crossing
    paint = np.zeros((H, W), np.float32)
    paint_col = np.zeros((H, W, 3), np.float32)
    od = c.open_d
    yellow = np.array([0.78, 0.68, 0.32], np.float32)
    white = np.array([0.82, 0.83, 0.82], np.float32)
    ridge = (od >= ndi.maximum_filter(od, size=5) - 0.25) & (od >= CENTRE[0]) & (od <= CENTRE[1])
    ridge = ndi.binary_dilation(ridge, iterations=1)
    xx, yy = g.xx.astype(int), g.yy.astype(int)
    dashes = ridge & ((c.hstreet & (xx % 40 < 22)) | (c.vstreet & (yy % 40 < 22)))
    dashes &= ~line(c.crossing, 1, 34) & ~line(c.crossing, 0, 34)
    paint[dashes] = 1
    paint_col[dashes] = yellow
    zebra = (c.hstreet & line(c.crossing, 1, 26) & ~line(c.crossing, 1, 8) & (yy % 14 < 7)) | \
            (c.vstreet & line(c.crossing, 0, 26) & ~line(c.crossing, 0, 8) & (xx % 14 < 7))
    zebra &= c.wall_d >= KERB + 5
    paint[zebra] = 1
    paint_col[zebra] = white
    wear = worn(H, W, seed + 3)
    pa = np.clip(blur(paint, 0.6) * wear * 0.65, 0, 1)
    shade = img.mean(-1, keepdims=True) / 0.25
    img = img * (1 - pa[..., None]) + np.clip(paint_col * np.clip(shade, 0.7, 1.15), 0, 1) * pa[..., None]
    # light from the sky: brighter in the open, darker close to the buildings
    sky = 0.84 + 0.22 * blur(np.clip(c.wall_d / 80, 0, 1), 14)
    img *= (sky * clouds)[..., None]
    # chasms: collapsed road into the subway, darker the deeper in
    inside = ndi.distance_transform_edt(g.chasmb).astype(np.float32)
    ch = tiled(g, chasm_t, 0.45, off=(37, 11))
    ch = ch / max(ch.mean(), 1e-3) * 0.12 * (1.1 - 0.6 * np.clip(inside / 60, 0, 1))[..., None]
    img = img * (1 - g.chasm[..., None]) + ch * g.chasm[..., None]
    # the broken edge: a ragged band of cracked, darker asphalt and a light broken rim
    rough = blur(rng.random((H, W)), 1.5)
    rough = (rough - rough.mean()) / (rough.std() + 1e-6)
    lip = c.open & (c.chasm_d <= 7 + 3 * rough)
    img *= (1 - 0.35 * blur(lip, 1.0))[..., None]
    rim = c.open & (c.chasm_d <= 1.8)
    img = img + 0.16 * blur(rim, 0.6)[..., None]
    # ambient occlusion where walls meet the floor
    ao = blur(np.maximum(g.side, g.wr), 5)
    img *= (1 - 0.45 * ao * (1 - g.wr) * (1 - g.side))[..., None]
    # roofs: each building its own roof texture, inside a light concrete parapet
    lab = c.lab
    top = np.zeros_like(img)
    conc = tiled(g, conc_t, 0.4, off=(5, 71))
    conc = conc / conc.mean() * 0.6
    for k, name in enumerate(ROOFS):
        mask = np.isin(lab, np.flatnonzero(c.roof == k) + 1)
        if not mask.any(): continue
        t = load(name)
        a = tiled(g, t, 0.45, 0.0, off=(k * 97.0, k * 41.0))
        b = tiled(g, t, 0.45, np.pi / 2, off=(k * 31.0, k * 13.0))
        turned = np.isin(lab, np.flatnonzero((c.roof == k) & (c.rot == 1)) + 1)
        tex = np.where(turned[..., None], b, a)
        tex = tex / tex[mask].mean() * 0.6
        top = np.where(mask[..., None], tex, top)
    top = np.where(c.buildings[..., None], top, conc)
    # parapet: a 5 px coping round each roof, the roof itself a step lower (a soft inner shadow)
    rim = np.clip(1 - (g.dist - 5) / 1.2, 0, 1) * c.buildings
    inner = np.clip((g.dist - 5) / 4, 0, 1) * c.buildings
    top = top * (1 - rim[..., None]) + conc * 1.12 * rim[..., None]
    top *= (1 - 0.22 * np.clip(1 - (g.dist - 5) / 3, 0, 1) * inner)[..., None]
    # bevel lit from the top-left
    hgt = np.clip(g.dist / 4.0, 0, 1); hgt = blur(hgt * hgt * (3 - 2 * hgt), 0.7)
    gy, gx = np.gradient(hgt)
    nz = 0.18
    lam = (-gx * -0.55 - gy * -0.6 + nz * 0.58) / np.sqrt(gx * gx + gy * gy + nz * nz)
    top *= (0.72 + 0.4 * lam)[..., None]
    top *= (1 - 0.25 * np.clip(1 - g.dist / 1.2, 0, 1))[..., None]
    # facades: darkened copies of the roof art, scaled down toward the camera point one step at
    # a time, each building only as many steps as it is tall
    sd = opts['sides']
    hgt_of = np.concatenate([[0], c.height])[lab]
    facade = blur(top.mean(-1), 2)[..., None] * np.array([0.92, 0.95, 1.0], np.float32)
    for i in range(len(g.steps) - 1, -1, -1):
        coords, _ = g.steps[i]
        tall = (hgt_of > i).astype(np.float32) * g.wr
        m = ndi.map_coordinates(tall, coords, order=1, mode='constant')
        if not m.any(): continue
        copy = np.stack([ndi.map_coordinates(facade[..., k], coords, order=1, mode='nearest') for k in range(3)], -1)
        # window rows on the tall facades: a faint banding every 3 copies
        band = 0.9 if i % 3 == 1 else 1.0
        copy *= sd['darken'] * sd['fade'] ** i * band
        m = (m * (1 - g.wr))[..., None]
        img = img * (1 - m) + copy * m
    return img * (1 - g.wr[..., None]) + top * g.wr[..., None]


def grey_day(img):
    """Grey day: colours muted, a cool cast, a soft overall haze."""
    img = grey(img, 0.3)
    img = img * np.array([0.97, 0.99, 1.03], np.float32)
    return img * 0.96 + 0.025


def night_ambient(img):
    """Night, before the lights go on: the daylight art dimmed to moonlight, cold and grey."""
    img = grey(img, 0.45)
    return img * np.array([0.30, 0.34, 0.44], np.float32)


def night(img):
    """Night, after the lights: deep blue shadows, a little contrast, the lit areas kept warm."""
    lum = img.mean(-1, keepdims=True)
    lift = np.array([0.012, 0.016, 0.03], np.float32) * (1 - np.clip(lum * 3, 0, 1))
    return np.clip((img - 0.02) * 1.08 + lift, 0, 1)


def night_light(lighting, g):
    """Night: the light pools fall on the streets, hardly on the roofs, and many lamps
    together saturate softly instead of washing out."""
    lighting = 1 - np.exp(-lighting)
    return lighting * (1 - 0.75 * g.wr)[..., None]


# level.json art.grade picks one ("grey day" when not given). AMBIENT runs on the art and its
# decor before the decor lights are added, LIGHT on the lights' pools, GRADES on the finished art.
GRADES = {'grey day': grey_day, 'night': night}
AMBIENT = {'night': night_ambient}
LIGHT = {'night': night_light}


def grade(img, name=None):
    return GRADES[name or 'grey day'](img)


def ambient(img, name=None):
    f = AMBIENT.get(name or 'grey day')
    return f(img) if f else img


def light(lighting, g, name=None):
    f = LIGHT.get(name or 'grey day')
    return f(lighting, g) if f else lighting
