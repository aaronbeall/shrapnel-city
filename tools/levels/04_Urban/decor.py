"""04 Urban's own decor, added to the decor the art kit places.

    python tools/art/bake.py 04_Urban place          # the city kit's decor (replaces decor.json)
    python tools/levels/04_Urban/decor.py            # + Urban's own (replaces only its own)
    python tools/art/bake.py 04_Urban bake

Urban's own sprites are the sheet tools/art/parts/decor/city-urban (generated by
tools/art/gen_city.sh city-urban). The robots have rezoned downtown as a patrol route, so:
- red chevrons are painted down every tank patrol lane, pointing the way the tanks drive,
  read from pathNodes.json (so the paint follows the loops if they're edited), with tread
  tracks worn along them
- overlord emblems are painted on the tower's roof and in the streets, and landing pads on
  two roofs (the roof equipment under them is cleared)
- a striped stop bar marks the checkpoint gate on both sides

Entries with a city-urban sprite are this tool's: running it again replaces them and leaves
the rest of decor.json alone. bake.py place --only <kit types> keeps them too; a full
bake.py place drops them, so run this again after one.
"""
import json
import math
import os
import random
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(ROOT, 'levels', '04_Urban')
sys.path.insert(0, os.path.join(ROOT, 'tools', 'art'))
from bake import write_decor  # noqa: E402

CAT = 'city-urban'
EMBLEMS = (0, 1, 3, 4)           # shield, fist in a cog, triangle eye, round eye
CHEVRONS = tuple(range(6, 12))   # point right
TREADS = tuple(range(12, 22))    # horizontal
BARS = (22, 23, 24)              # horizontal
PADS = (25, 26, 27)
SIZES = json.load(open(os.path.join(ROOT, 'tools', 'art', 'parts', 'decor', 'index.json')))[CAT]


def spr(i): return f'{CAT}/{i:02d}.png'


def size(i): return SIZES[i]['w'], SIZES[i]['h']


def main():
    rng = random.Random(4041)
    decor = json.load(open(os.path.join(D, 'decor.json')))
    decor = [e for e in decor if not e['sprite'].startswith(CAT + '/')]
    nodes = json.load(open(os.path.join(D, 'pathNodes.json')))
    features = json.load(open(os.path.join(D, 'features.json')))
    doors = json.load(open(os.path.join(D, 'doors.json')))
    by = {n['name']: n for n in nodes}
    under, over = [], []   # painted under the kit's decor / on top of it

    def put(i, x, y, length, rot, effect='paint', strength=None, where=under):
        w, h = size(i)
        e = {'sprite': spr(i), 'x': round(x), 'y': round(y), 'scale': round(length / w, 4), 'rotation': round(rot % 360, 2), 'effect': effect}
        if strength is not None: e['strength'] = strength
        where.append(e)

    # patrol lanes: chevrons every 64 px pointing along the loop, tread tracks either side
    for n in nodes:
        m = by[n['props']['connections'][0]['$ref']]
        ax, ay, bx, by_ = n['x'], n['y'], m['x'], m['y']
        L = math.hypot(bx - ax, by_ - ay)
        ux, uy = (bx - ax) / L, (by_ - ay) / L
        rot = -math.degrees(math.atan2(uy, ux))  # the sprite points right; rotation is counter-clockwise
        t = 56.0
        while t < L - 50:
            put(rng.choice(CHEVRONS), ax + ux * t, ay + uy * t, 24, rot)
            t += 64
        t = 40.0 + rng.uniform(0, 40)
        while t < L - 70:
            side = rng.choice((-1, 1))
            put(rng.choice(TREADS), ax + ux * t - uy * side * 15, ay + uy * t + ux * side * 15, rng.uniform(60, 110), rot)
            t += rng.uniform(110, 190)

    # emblems: a big one on the tower's roof, smaller ones in the streets and on the plaza
    put(EMBLEMS[1], 800, 559, 120, 0)
    put(EMBLEMS[3], 260, 1042, 56, 0)
    put(EMBLEMS[0], 76, 380, 50, 0)
    put(EMBLEMS[2], 1524, 450, 56, 180)
    put(EMBLEMS[3], 600, 76, 56, 0)
    # landing pads on two roofs
    pads = [(981, 237, 96), (1343, 881, 90)]
    for (x, y, d), i in zip(pads, (PADS[0], PADS[2])):
        put(i, x, y, d, 0, where=over)
    # clear the kit's roof equipment from under the pads and the tower emblem
    clear = pads + [(800, 559, 120)]
    decor = [e for e in decor if not (e['sprite'].startswith('city-roof') and any(math.hypot(e['x'] - x, e['y'] - y) < d / 2 + 14 for x, y, d in clear))]
    # the checkpoint: stop bars either side of the gate
    for dr in doors:
        put(BARS[0], dr['x'], dr['y'] + 26, 96, 0)
        put(BARS[1], dr['x'], dr['y'] - 26, 96, 0)
    # keep the exit pad clean
    ex = next(f for f in features if f['symbol'].endswith('exit_mc'))
    under = [e for e in under if math.hypot(e['x'] - ex['x'], e['y'] - ex['y']) > 60]

    decor = under + decor + over
    write_decor(os.path.join(D, 'decor.json'), decor)
    print(f'decor.json: {len(under) + len(over)} Urban decor placements, {len(decor)} in all')


if __name__ == '__main__':
    main()
