"""05 Gateway's own decor, added to the decor the city kit places.

    python tools/art/bake.py 05_Gateway place          # the city kit's decor (replaces decor.json)
    python tools/levels/05_Gateway/decor.py            # + Gateway's own (replaces only its own)
    python tools/art/bake.py 05_Gateway bake

Gateway's sprites are the sheet tools/art/parts/decor/city-gateway (generated by
tools/art/gen_city.sh city-gateway, no reference image). This tool also writes key-coloured
copies of the hazard stripes and keycard symbols to tools/art/parts/decor/city-gateway-keys/.
It reads the level files, so the paint follows doors, locks and rails if they're edited:
- every keycard door gets hazard stripes in its key colour across both faces, and a keycard
  symbol in that colour on the floor by its lock pad
- the queue pen's lanes get painted arrows and footprints showing the way through the
  switchbacks
- inspection bays are painted in the lane either side of the customs hall
- the strip's ditch crossings are edged with hazard stripes
- searchlights on the gate towers, the customs hall and the barracks
- an overlord emblem in the gate hall, the strip and the yard
- the kit's planters are removed: every small wall here is a booth, pillar, desk or rail

Entries with a city-gateway sprite are this tool's: running it again replaces them and leaves
the rest of decor.json alone.
"""
import json
import math
import os
import random
import sys

import numpy as np
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(ROOT, 'levels', '05_Gateway')
DEC = os.path.join(ROOT, 'tools', 'art', 'parts', 'decor')
sys.path.insert(0, os.path.join(ROOT, 'tools', 'art'))
from bake import write_decor  # noqa: E402

CAT = 'city-gateway'
STRIPES = (0, 4, 8, 11, 14)      # horizontal hazard bands, pale stripes recoloured per key
ARROWS = (1, 5, 9, 13)           # point right
FEET = (2, 6, 10, 15)            # footprints (pointing up)
BAYS = (17, 18, 19)              # inspection bays, horizontal
LAMPS = (28, 29, 30)             # searchlights, seen from above
CARDS = (31, 32)                 # keycard symbols
EMBLEMS = ('city-urban/00.png', 'city-urban/01.png', 'city-urban/03.png', 'city-urban/04.png')
KEY_RGB = {'yellowKey': (255, 205, 40), 'blueKey': (60, 150, 255), 'redKey': (235, 50, 40)}
SIZES = json.load(open(os.path.join(DEC, 'index.json')))


def spr(i): return f'{CAT}/{i:02d}.png'


def size(i): return SIZES[CAT][i]['w'], SIZES[CAT][i]['h']


def band(i, key=None):
    """A short piece (4:1) of hazard band i, recoloured in the key's colour if given; returns
    its sprite path and width. The sheet's bands are 18:1, too thin to read at door width."""
    name = f'{CAT}-keys/{i:02d}-{key or "plain"}.png'
    im = Image.open(os.path.join(DEC, spr(i))).convert('RGBA')
    im = im.crop((0, 0, im.height * 4, im.height))
    return _recolour(im, name, key), im.width


def tinted(i, key):
    """A copy of sprite i with its pale paint recoloured in the key's colour."""
    return _recolour(Image.open(os.path.join(DEC, spr(i))).convert('RGBA'), f'{CAT}-keys/{i:02d}-{key}.png', key)


def _recolour(im, name, key):
    out = os.path.join(DEC, name)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    a = np.array(im, np.float32) / 255
    if key is None:
        Image.fromarray((a * 255 + 0.5).astype(np.uint8)).save(out)
        return name
    lum = a[..., :3].mean(-1, keepdims=True)
    pale = np.clip((lum - 0.45) / 0.3, 0, 1)
    col = np.array(KEY_RGB[key], np.float32) / 255
    a[..., :3] = a[..., :3] * (1 - pale) + (col * (0.55 + 0.5 * lum)) * pale
    Image.fromarray((np.clip(a, 0, 1) * 255 + 0.5).astype(np.uint8)).save(out)
    return name


def main():
    rng = random.Random(5051)
    decor = json.load(open(os.path.join(D, 'decor.json')))
    decor = [e for e in decor if not e['sprite'].startswith(CAT) and not e['sprite'].startswith('city-plants/')]
    load = lambda n: json.load(open(os.path.join(D, n)))
    doors, pick, feats = load('doors.json'), load('powerups.json'), load('features.json')
    under, over = [], []

    def put(sprite, w, x, y, length, rot, effect='paint', strength=None, where=under):
        e = {'sprite': sprite, 'x': round(x), 'y': round(y), 'scale': round(length / w, 4), 'rotation': round(rot % 360, 2)}
        if effect: e['effect'] = effect
        if strength is not None: e['strength'] = strength
        where.append(e)

    # the keycard doors: stripes across both faces of the wall, a keycard by the lock
    locks = {p['props']['unlock'].split(':')[0]: p for p in pick if p['props'].get('type') == 'lock'}
    for dr in doors:
        lk = locks.get(dr['props']['id'])
        if not lk: continue
        key = lk['props']['item']
        side = 1 if lk['y'] > dr['y'] else -1
        reach = abs(lk['y'] - dr['y']) - 18          # the wall face on the lock's side
        for s in (side, -side):
            i = rng.choice(STRIPES)
            put(*band(i, key), dr['x'], dr['y'] + s * (reach + 9), 58, 0, effect=None)
        c = rng.choice(CARDS)
        put(tinted(c, key), size(c)[0], dr['x'], lk['y'] + 30, 30, 0)

    # the queue pen: arrows and footprints through the switchbacks (rails from collision.json)
    shapes = json.load(open(os.path.join(D, 'collision.json')))
    rails = sorted({round(float(s['d'].split()[2]) + 4) for s in shapes if s['name'].startswith('queue rail')})
    lanes = [(a + b) / 2 for a, b in zip(rails, rails[1:])]
    for k, y in enumerate(reversed(lanes)):        # south lane first: you enter it from the west
        east = k % 2 == 0
        for x in range(110, 500, 120):
            i = rng.choice(ARROWS)
            put(spr(i), size(i)[0], x, y, 34, 0 if east else 180)
            f = rng.choice(FEET)
            put(spr(f), size(f)[0], x + (-36 if east else 36), y, 16, 270 if east else 90)

    # inspection bays either side of the customs hall's lane
    yl = next(d for d in doors if locks.get(d['props']['id'], {}).get('props', {}).get('item') == 'yellowKey')
    for dy in (-150, 128):
        i = rng.choice(BAYS)
        put(spr(i), size(i)[0], yl['x'], yl['y'] + dy, 104, 90)

    # the strip's ditch crossings, edged with hazard stripes (read from the ditch shapes' gaps)
    ditch = [s for s in shapes if s['name'].startswith('ditch ') and 'pit' not in s['name'] and 'island' not in s['name']]
    edges = []
    for s in ditch:
        xs = [float(t) for t in s['d'].replace('M', ' ').replace('L', ' ').replace('Z', ' ').split()[0::2]]
        ys = [float(t) for t in s['d'].replace('M', ' ').replace('L', ' ').replace('Z', ' ').split()[1::2]]
        edges += [(min(xs), (min(ys) + max(ys)) / 2), (max(xs), (min(ys) + max(ys)) / 2)]
    for x, y in edges:
        if 30 < x < 1410:
            i = rng.choice(STRIPES)
            put(*band(i), x + (8 if any(abs(x - x2) < 100 and x2 > x for x2, _ in edges) else -8), y, 50, 90, effect=None)

    # searchlights on the gate towers, the customs hall and the barracks roof
    for x, y in ((1132, 50), (1348, 50), (300, 1140), (1100, 1140), (1147, 1440), (1400, 1376)):
        i = rng.choice(LAMPS)
        put(spr(i), size(i)[0], x, y, 26, rng.uniform(0, 360), effect='glow', strength=0.7, where=over)

    # overlord emblems: the gate hall floor, the strip, the inspection yard
    for (x, y, d), em in zip(((680, 168, 86), (731, 450, 44), (1020, 820, 60)), (EMBLEMS[1], EMBLEMS[2], EMBLEMS[0])):
        w = SIZES['city-urban'][int(em.split('/')[1][:2])]['w']
        put(em, w, x, y, d, 0)

    # keep the exit pad clean
    ex = next(f for f in feats if f['symbol'].endswith('exit_mc'))
    under = [e for e in under if math.hypot(e['x'] - ex['x'], e['y'] - ex['y']) > 60]

    decor = under + decor + over
    write_decor(os.path.join(D, 'decor.json'), decor)
    print(f'decor.json: {len(under) + len(over)} Gateway decor placements, {len(decor)} in all')


if __name__ == '__main__':
    main()
